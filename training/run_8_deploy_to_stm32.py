"""
run_8_deploy_to_stm32.py
Automatically finds the C headers generated by STM32Cube.AI Studio and 
copies them into your Voice_Command_Assistant_STM32 main project folders.
"""
import os
import shutil
import glob

# Search in the current training directory for any folder ending in "-code"
# (which is what STEDGEAI generates, e.g., custom_model.tflite-STM32F407G-DISC1-code)
def get_stedgeai_output_dir():
    folders = [d for d in os.listdir('.') if os.path.isdir(d) and d.endswith("-code")]
    if not folders:
        return None
    # If multiple exist, pick the most recently modified one
    folders.sort(key=os.path.getmtime, reverse=True)
    return folders[0]

def main():
    print("\n--- STM32 Firmware Auto-Deploy ---")
    
    st_dir = get_stedgeai_output_dir()
    if not st_dir:
        print("ERROR: Could not find any STEDGEAI output folder (e.g., '*-code').")
        print("Please drag your .tflite file into STM32Cube AI Studio and generate the C code first!")
        return

    print(f"Found code generation folder: {st_dir}")

    # The target paths relative to this script's directory (training/)
    target_src = os.path.join("..", "Voice_Command_Assistant_STM32", "Core", "Src")
    target_inc = os.path.join("..", "Voice_Command_Assistant_STM32", "Core", "Inc")

    if not os.path.exists(target_src) or not os.path.exists(target_inc):
        print("ERROR: Could not find the target STM32 Core/Src or Core/Inc directories.")
        return

    files_to_copy = {
        "network.c": target_src,
        "network_data.c": target_src,
        "network.h": target_inc,
        "network_data.h": target_inc
    }

    success_count = 0
    for filename, dest_dir in files_to_copy.items():
        source_file = os.path.join(st_dir, filename)
        
        if not os.path.exists(source_file):
            print(f"  [X] Missing {filename} in {st_dir}")
            continue

        dest_file = os.path.join(dest_dir, filename)
        try:
            shutil.copy2(source_file, dest_file)
            print(f"  [✓] Copied {filename} -> {os.path.normpath(dest_dir)}")
            success_count += 1
        except Exception as e:
            print(f"  [X] Failed to copy {filename}: {e}")

    if success_count == len(files_to_copy):
        print("\nSUCCESS: All AI files deployed to STM32 project!")
        print("You can now open STM32CubeIDE and flash the new model.")
    else:
        print("\nWARNING: Some files were not copied correctly.")

if __name__ == "__main__":
    main()
